def num(s):
    return pd.to_numeric(s.astype(str).str.replace('\u00a0', '').str.replace(' ', '')
                         .str.replace(',', '.').str.replace('–', '-'), errors='coerce')

# ---------- лесничества: пожары, площади, рубки ----------
xl = pd.ExcelFile(SRC / 'ущербы.xlsx')
sheets = {'Вырубка, тыс. куб. м. ': 'cut_k_m3', 'Пожары': 'fires',
          'Площади пожаров, тыс. га': 'fire_area_kha'}
parts = []
for sh, col in sheets.items():
    d = xl.parse(sh)
    d = d[d['Лесничество'] != 'Итого'].copy()
    d['Лесничество'] = d['Лесничество'].str.strip().str.replace('–', '-', regex=False)  # в листах разные тире
    yrs = [c for c in d.columns if str(c).isdigit()]
    d = d.melt(id_vars=['Лесничество', 'Регион'], value_vars=yrs, var_name='year', value_name=col)
    d['year'] = d['year'].astype(int)
    d[col] = num(d[col])
    parts.append(d.set_index(['Лесничество', 'Регион', 'year']))
forest = pd.concat(parts, axis=1).reset_index()
forest.columns = ['forestry', 'region', 'year', 'cut_k_m3', 'fires', 'fire_area_kha']
forest['region'] = forest.region.map({'ИРКУТСКАЯ ОБЛАСТЬ': 'Иркутская область', 'РЕСПУБЛИКА БУРЯТИЯ': 'Республика Бурятия',
                                      'ЗАБАЙКАЛЬСКИЙ КРАЙ': 'Забайкальский край'})
forest['lat'] = forest.forestry.map(lambda x: FOREST_XY[x][0])
forest['lon'] = forest.forestry.map(lambda x: FOREST_XY[x][1])
forest.to_csv(OUT / 'forestry.csv', index=False, encoding='utf-8')

